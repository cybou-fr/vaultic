#!/usr/bin/env python3
"""Build the Windows icon and the resource that embeds it in vaultic.exe. NO CI.

    py scripts/make-icon.py            icon + resources (needs Go and windres)
    py scripts/make-icon.py --resources-only
                                       only regenerate the resource file (version
                                       info) from the committed assets/vaultic.ico

The icon is the application's own SVG, rendered once by Fyne at 512 px and
scaled down with Pillow (Fyne's SVG renderer draws the thin strokes wrongly at
very small sizes), then packed into assets/vaultic.ico. Needs: pip install pillow. The resource (assets/vaultic.rc, generated)
holds the icon and the version information shown in Explorer's Properties; it is
compiled with windres to cmd/restic/vaultic_windows_amd64.syso, which Go links
automatically on Windows. The .syso is committed, so building does not need
windres; build.py refreshes it when windres is available.
"""
import argparse
import glob
import os
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
SIZES = (16, 24, 32, 48, 64, 128, 256)
AUTHOR = "Stanislav SAVELIEV"


def find_windres():
    exe = shutil.which("windres")
    if exe:
        return exe
    for pattern in (r"C:\Qt\Tools\mingw*\bin", r"C:\msys64\ucrt64\bin", r"C:\msys64\mingw64\bin"):
        for folder in sorted(glob.glob(pattern)):
            candidate = Path(folder) / "windres.exe"
            if candidate.exists():
                return str(candidate)
    return None


def export_pngs(folder):
    env = dict(os.environ, VAULTIC_ICON_DIR=str(folder))
    subprocess.run(["go", "test", "./cmd/restic", "-run", "^TestVaulticExportIcon$", "-count=1"], cwd=ROOT, env=env, check=True)


def scaled_pngs(folder):
    """PNG bytes of the icon for every size, scaled from the 512 px render."""
    try:
        from PIL import Image
    except ImportError:
        sys.exit("Pillow is required to scale the icon: pip install pillow")
    import io
    normal = Image.open(Path(folder) / "icon-512.png").convert("RGBA")
    bold = Image.open(Path(folder) / "icon-bold-512.png").convert("RGBA")
    out = []
    for size in SIZES:
        buffer = io.BytesIO()
        master = bold if size <= 48 else normal  # heavier strokes stay visible when small
        master.resize((size, size), Image.LANCZOS).save(buffer, "PNG")
        out.append((size, buffer.getvalue()))
    return out


def write_ico(images, path):
    """ICO file whose images are PNGs (supported since Windows Vista)."""
    header = struct.pack("<HHH", 0, 1, len(images))
    offset = 6 + 16 * len(images)
    directory, data = b"", b""
    for size, blob in images:
        dim = 0 if size >= 256 else size
        directory += struct.pack("<BBBBHHII", dim, dim, 0, 0, 1, 32, len(blob), offset + len(data))
        data += blob
    path.write_bytes(header + directory + data)


def version_parts(version):
    numbers = [int(p) for p in version.split("-")[0].split(".")[:3]]
    return numbers + [0] * (3 - len(numbers)) + [0]


def write_rc(path, version):
    major, minor, patch, build = version_parts(version)
    path.write_text(f'''// Generated by scripts/make-icon.py: do not edit.
1 ICON "vaultic.ico"
1 VERSIONINFO
FILEVERSION {major},{minor},{patch},{build}
PRODUCTVERSION {major},{minor},{patch},{build}
FILEFLAGSMASK 0x3fL
FILEOS 0x40004L
FILETYPE 0x1L
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904B0"
    BEGIN
      VALUE "CompanyName", "{AUTHOR}"
      VALUE "FileDescription", "Vaultic - encrypted backups"
      VALUE "FileVersion", "{version}"
      VALUE "InternalName", "vaultic"
      VALUE "LegalCopyright", "Copyright 2026 {AUTHOR}"
      VALUE "OriginalFilename", "vaultic.exe"
      VALUE "ProductName", "Vaultic"
      VALUE "ProductVersion", "{version}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
''', encoding="utf-8")


def compile_resources(version):
    windres = find_windres()
    if not windres:
        return False
    rc = ASSETS / "vaultic.rc"
    write_rc(rc, version)
    out = ROOT / "cmd" / "restic" / "vaultic_windows_amd64.syso"
    subprocess.run([windres, "-O", "coff", "-F", "pe-x86-64", "-i", rc.name, "-o", str(out)], cwd=ASSETS, check=True)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--resources-only", action="store_true")
    args = parser.parse_args()
    version = (ROOT / "VAULTIC_VERSION").read_text(encoding="utf-8").strip()
    ASSETS.mkdir(exist_ok=True)
    if not args.resources_only:
        with tempfile.TemporaryDirectory() as tmp:
            export_pngs(tmp)
            write_ico(scaled_pngs(tmp), ASSETS / "vaultic.ico")
        print("wrote", ASSETS / "vaultic.ico")
    if not (ASSETS / "vaultic.ico").is_file():
        sys.exit("assets/vaultic.ico is missing: run without --resources-only")
    if compile_resources(version):
        print("wrote cmd/restic/vaultic_windows_amd64.syso for version", version)
    else:
        print("windres not found: the committed .syso was left unchanged")


if __name__ == "__main__":
    main()
